/// Invalidate all lockfile caches. Call this after modifying a lockfile.
pub fn invalidate_caches() {
    if let Ok(mut cache) = ALL_LOCKFILES_CACHE.lock() {
        cache.clear();
    }
    if let Ok(mut cache) = SINGLE_LOCKFILE_CACHE.lock() {
        cache.clear();
    }
    if let Ok(mut cache) = LOCKFILES_BY_PRECEDENCE_CACHE.lock() {
        cache.clear();
    }
    if let Ok(mut cache) = LEGACY_LOCKFILE_PATHS_CACHE.lock() {
        cache.clear();
    }
}

pub const CURRENT_LOCKFILE_VERSION: u32 = 3;
const FORGE_IDS_LOCKFILE_VERSION: u32 = 3;
// Keep the dates format bumps entered mise here. An older format gets a
// warning six calendar months after the first newer format was introduced.
const LOCKFILE_VERSION_DATES: &[(u32, jiff::civil::Date)] = &[
    (1, jiff::civil::date(2026, 8, 23)),
    (2, jiff::civil::date(2026, 9, 13)),
    (3, jiff::civil::date(2026, 9, 27)),
];

fn outdated_lockfile_version(version: u32, today: jiff::civil::Date) -> bool {
    LOCKFILE_VERSION_DATES
        .iter()
        .any(|&(bumped_version, date)| {
            bumped_version > version
                && date
                    .checked_add(jiff::Span::new().months(6))
                    .is_ok_and(|deadline| today > deadline)
        })
}

/// Warn about active lockfiles whose format has been superseded for six months.
pub fn warn_outdated_lockfiles(config: &Config) {
    if !Settings::get().lockfile_enabled() {
        return;
    }
    let discovery = config.lockfile_discovery(|| derive_lockfile_discovery(config));
    if discovery
        .outdated_warning_checked
        .swap(true, Ordering::Relaxed)
    {
        return;
    }
    let monorepo_root = config.monorepo_lockfile_root();
    let today = jiff::Zoned::now().date();
    let mut targets = HashMap::new();
    let mut roots = HashSet::new();
    for (path, cf) in &config.config_files {
        if !cf.source().is_mise_toml() {
            continue;
        }
        let (target, _) = lockfile_path_for_config(path, monorepo_root.as_deref());
        let global = crate::config::is_global_config(path);
        if let Some(root) = target.parent() {
            roots.insert((root.to_path_buf(), global));
        }
        targets.insert(target, global);
    }
    let mut seen = HashSet::new();
    for (root, global) in roots {
        for candidate in active_lockfile_paths_in_dir(&root) {
            if !seen.insert(candidate.clone()) || !candidate.exists() {
                continue;
            }
            let remedy = match (targets.get(&candidate), global) {
                (Some(&true), _) => "run `mise lock --global --upgrade`",
                (Some(&false), _) => "run `mise lock --upgrade` from its config directory",
                (None, true) => {
                    "add a matching config and run `mise lock --global --upgrade`, or remove the lockfile if no longer needed"
                }
                (None, false) => {
                    "add a matching config and run `mise lock --upgrade`, or remove the lockfile if no longer needed"
                }
            };
            warn_outdated_lockfile(&candidate, today, remedy);
        }
    }
    for candidate in &discovery.legacy_lockfiles {
        if !seen.insert(candidate.clone()) || !candidate.exists() {
            continue;
        }
        warn_outdated_lockfile(
            candidate,
            today,
            "run `mise lock --upgrade` at the monorepo root",
        );
    }
}

/// `mise lock` already reports old formats and can upgrade them in this run.
pub fn suppress_outdated_lockfile_warning(config: &Config) {
    let discovery = config.lockfile_discovery(|| derive_lockfile_discovery(config));
    discovery
        .outdated_warning_suppressed
        .store(true, Ordering::Relaxed);
    discovery
        .outdated_warning_checked
        .store(true, Ordering::Relaxed);
}

fn warn_outdated_lockfile(path: &Path, today: jiff::civil::Date, remedy: &str) {
    if let Ok(lockfile) = Lockfile::read(path)
        && outdated_lockfile_version(lockfile.lockfile_version(), today)
    {
        warn_once!(
            "{} uses old lockfile format version {}; {remedy}",
            display_path(path),
            lockfile.lockfile_version()
        );
    }
}

fn active_lockfile_paths_in_dir(root: &Path) -> Vec<PathBuf> {
    let mut paths = Vec::new();
    for env_name in env::MISE_ENV.iter().chain(env::AUTO_ENV_NAMES.iter().rev()) {
        paths.push(root.join(format!("mise.{env_name}.local.lock")));
    }
    paths.push(root.join("mise.local.lock"));
    for env_name in env::MISE_ENV.iter().chain(env::AUTO_ENV_NAMES.iter().rev()) {
        paths.push(root.join(format!("mise.{env_name}.lock")));
    }
    paths.push(root.join("mise.lock"));
    paths
}

#[derive(Debug, Clone, Default, Serialize, Deserialize)]
pub struct AubeLock {
    pub graph: toml::Table,
    #[serde(skip)]
    pub graph_text: String,
    #[serde(skip)]
    pub project: Option<String>,
}

impl PartialEq for AubeLock {
    fn eq(&self, other: &Self) -> bool {
        self.graph == other.graph
    }
}
impl Eq for AubeLock {}

impl AubeLock {
    pub(crate) fn from_yaml(contents: &str) -> Result<Self> {
        let value: yaml::Value = yaml::from_str(contents)?;
        let toml::Value::Table(graph) = yaml_to_toml(value)? else {
            bail!("aube lockfile must contain a mapping");
        };
        Ok(Self {
            graph,
            graph_text: contents.to_owned(),
            project: None,
        })
    }

    pub(crate) fn to_yaml(&self) -> Result<String> {
        if !self.graph_text.is_empty() {
            return Ok(self.graph_text.clone());
        }
        let value = toml_to_yaml(toml::Value::Table(self.graph.clone()));
        Ok(yaml::to_string(&value)?)
    }

    pub(crate) fn legacy_identity(&self) -> Result<String> {
        use sha2::{Digest, Sha256};
        let mut hasher = Sha256::new();
        hash_canonical_toml(&mut hasher, &toml::Value::Table(self.graph.clone()));
        Ok(hex::encode(hasher.finalize()))
    }
}

