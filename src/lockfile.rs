/// Global caches for lockfile data - declared here so invalidation can access them
static ALL_LOCKFILES_CACHE: Lazy<Mutex<HashMap<Vec<PathBuf>, Arc<Lockfile>>>> =
    Lazy::new(Default::default);
static SINGLE_LOCKFILE_CACHE: Lazy<Mutex<HashMap<Vec<PathBuf>, Arc<Lockfile>>>> =
    Lazy::new(Default::default);
type LockfilesByPrecedence = HashMap<Vec<PathBuf>, Arc<Vec<Lockfile>>>;
/// The lockfiles [`read_all_lockfiles`] merges, highest precedence first,
/// filled alongside its cache.
static LOCKFILES_BY_PRECEDENCE_CACHE: Lazy<Mutex<LockfilesByPrecedence>> =
    Lazy::new(Default::default);
type LegacyLockfilePathsCacheKey = (PathBuf, Option<bool>, Vec<String>);
static LEGACY_LOCKFILE_PATHS_CACHE: Lazy<
    Mutex<HashMap<LegacyLockfilePathsCacheKey, IndexSet<PathBuf>>>,
> = Lazy::new(Default::default);
/// What [`read_all_lockfiles`] derives once per [`Config`]: the paths that key
/// the shared cache, plus the monorepo/legacy discovery results the cache-miss
/// path needs, so a miss doesn't repeat that discovery.
pub(crate) struct LockfileDiscovery {
    cache_key: Vec<PathBuf>,
    monorepo_root: Option<PathBuf>,
    legacy_lockfiles: IndexSet<PathBuf>,
    outdated_warning_checked: AtomicBool,
    outdated_warning_suppressed: AtomicBool,
}

