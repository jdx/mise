// A real value for each key the reference has no whole example for, keyed by the key's path.
// The reference writes the key's snippet (where it goes, the keys beside it that make it
// valid) and puts this value on it, so `tools.<github:…>.checksum` reads like a checksum.
//
// Values are TOML, as they are written after the `=`. A key written for several backends or
// sections is listed once, under the first of these that applies:
//   `tools.<github:…>.x` for an option the forge backends share (`<*:…>` stands for any of
//   them), `tasks.<name>.x` for a task template's key, `daemons.<name>.x` for a daemon
//   provider's, `bootstrap.hooks.<phase>` for a bootstrap hook. A key below `platforms.<key>` has the value of the same key of the tool.
// config-reference-examples.test.ts checks that every snippet is valid mise.toml.

// `entries` with `prefix` in front of each path.
