const BACKEND = /<[a-z0-9-]+:…>/;

// Where `path` is looked up: itself, then the paths it shares a value with, nearest first.
export function candidates(path: string): string[] {
  const out = [path];
  const add = (p: string) => out.includes(p) || out.push(p);
  // a task template's, and a task's tool, env or vars, are written the same as the top level's
  const task = path.replace(/^task_templates\.<name>\./, "tasks.<name>.");
  add(task);
  add(task.replace(/^tasks\.<name>\.(tools|env|vars)\./, "$1."));
  for (const p of [...out]) {
    // `<github:…>` and the other backends of one shape share their options
    const wild = p.replace(BACKEND, "<*:…>");
    add(wild);
    // a platform's options are the tool's options
    add(p.replace(/\.platforms?\.<key>\./, "."));
    add(wild.replace(/\.platforms?\.<key>\./, "."));
    add(p.replace(/^daemon_providers\.<name>\./, "daemons.<name>."));
    // every bootstrap phase has the same hooks, and every shell the same options
    add(p.replace(/^(bootstrap\.hooks\.)[a-z_-]+/, "$1<phase>"));
    add(p.replace(/^(bootstrap\.mise_shell_activate\.)[a-z_]+/, "$1<shell>"));
  }
  return out;
}

// The value for the key at `path`, from the closest key that has one.
export function valueFor(path: string): string | undefined {
  for (const candidate of candidates(path)) {
    if (candidate in values) return values[candidate];
  }
  return undefined;
}
