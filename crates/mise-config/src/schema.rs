//! The JSON schema for the `mise.toml` sections whose types live in this crate.
//!
//! `schema/mise.json` is still partly written by hand. `mise run render:schema` replaces each
//! fragment listed here at its JSON pointer, the way it already fills in `$defs.settings` from
//! `settings.toml`. A section moves out of the hand-written part when its types gain a
//! `JsonSchema` derive here, and the test below fails while the committed file is stale.
//!
//! A field whose value stays raw TOML (so newer shapes warn instead of failing) has no Rust type
//! to describe it. Its schema stays hand-written under `$defs`, and the generated tree points at
//! it through [`refs`].

use schemars::generate::SchemaSettings;
use schemars::transform::RecursiveTransform;
use schemars::{JsonSchema, Schema, SchemaGenerator};
use serde_json::Value;

use crate::alias::Alias;
use crate::bootstrap::BootstrapTomlConfig;
use crate::daemons::{DaemonSettings, GroupDeclaration};
use crate::doctor::DoctorConfig;
use crate::history::HistoryTomlConfig;
use crate::launchd::LaunchdCalendarInterval;
use crate::min_version::MinVersionSpec;
use crate::monorepo::MonorepoConfig;
use crate::oci::OciConfig;
use crate::remote::InstallMiseTomlConfig;
use crate::task::{TaskConfig, TaskDecl};
use crate::tool_config::ToolConfig;
use crate::watch_files::WatchFile;
use crate::wrappers::CommandWrapper;

/// Each generated fragment, keyed by the JSON pointer it replaces in `schema/mise.json`.
pub fn fragments() -> Vec<(&'static str, Value)> {
    let mut generator = generator();
    let derived = vec![
        (
            "/properties/bootstrap",
            fragment::<BootstrapTomlConfig>(&mut generator),
        ),
        (
            "/properties/history",
            fragment::<HistoryTomlConfig>(&mut generator),
        ),
        (
            "/properties/wrappers/additionalProperties",
            fragment::<CommandWrapper>(&mut generator),
        ),
        (
            "/properties/daemons_settings",
            fragment::<DaemonSettings>(&mut generator),
        ),
        (
            "/properties/daemon_groups/additionalProperties",
            fragment::<GroupDeclaration>(&mut generator),
        ),
        ("/properties/oci", fragment::<OciConfig>(&mut generator)),
        ("/$defs/doctor", fragment::<DoctorConfig>(&mut generator)),
        (
            "/$defs/monorepo",
            fragment::<MonorepoConfig>(&mut generator),
        ),
        ("/$defs/tool_config", fragment::<ToolConfig>(&mut generator)),
        (
            "/$defs/watch_files/items",
            fragment::<WatchFile>(&mut generator),
        ),
        (
            "/$defs/bootstrap_remote_install_mise",
            fragment::<InstallMiseTomlConfig>(&mut generator),
        ),
        (
            "/$defs/launchd_calendar_interval",
            fragment::<LaunchdCalendarInterval>(&mut generator),
        ),
    ];
    // `task_props` is composed with `allOf` in `task` and `task_template`, which close it with
    // `unevaluatedProperties`; closing it here as well would reject every key they add.
    let mut task_props = fragment::<TaskDecl>(&mut generator);
    if let Some(object) = task_props.as_object_mut() {
        object.remove("additionalProperties");
    }
    let task_template = crate::task::template_schema(&task_props);
    let tasks = vec![
        ("/$defs/task_props", task_props),
        ("/$defs/task_template", task_template),
        ("/$defs/task_config", fragment::<TaskConfig>(&mut generator)),
    ];
    // Written by hand next to their parser, so they skip the generator's transforms and are
    // emitted exactly as written.
    let hand_written = crate::env::schema_fragments()
        .into_iter()
        .chain(crate::task::schema_fragments())
        .chain([
            (
                "/$defs/tool_alias_entry",
                Alias::json_schema(&mut generator),
            ),
            (
                "/$defs/tool_alias_versions",
                crate::alias::versions_schema(),
            ),
            (
                "/properties/min_version",
                MinVersionSpec::json_schema(&mut generator),
            ),
        ])
        .map(|(pointer, schema)| (pointer, schema.to_value()));
    derived
        .into_iter()
        .chain(tasks)
        .chain(hand_written)
        .collect()
}

/// `schema_with` functions that point at a `$defs` entry, for fields that share one definition.
///
/// Some entries are generated by [`fragments`]; the rest are still written by hand.
pub(crate) mod refs {
    use schemars::{Schema, SchemaGenerator, json_schema};

    macro_rules! refs {
        ($($name:ident),* $(,)?) => {$(
            pub(crate) fn $name(_: &mut SchemaGenerator) -> Schema {
                json_schema!({"$ref": concat!("#/$defs/", stringify!($name))})
            }
        )*};
    }

    refs!(
        bootstrap_apt_sources,
        bootstrap_dnf_repos,
        bootstrap_file_phase,
        bootstrap_hooks,
        bootstrap_macos_defaults,
        bootstrap_macos_dock,
        bootstrap_macos_finder,
        bootstrap_macos_keyboard,
        bootstrap_macos_trackpad,
        bootstrap_mise_shell_activate,
        bootstrap_remote_install_mise,
        env,
        launchd_calendar_interval,
        os_filter,
        task_watch,
        vars,
    );
}

/// Closes a `deny_unknown_fields` struct with `unevaluatedProperties`, the form the hand-written
/// file uses, in place of the `additionalProperties: false` schemars writes. The two accept the
/// same tables when the schema has no subschemas.
pub(crate) fn unevaluated(schema: &mut Schema) {
    if schema.get("additionalProperties") == Some(&Value::Bool(false)) {
        schema.remove("additionalProperties");
        schema.insert("unevaluatedProperties".into(), false.into());
    }
}

/// Writes an untagged enum's alternatives as `oneOf`, the form the hand-written file uses.
///
/// schemars writes `anyOf`. The alternatives of these enums never overlap, so the two accept
/// the same values.
pub(crate) fn one_of(schema: &mut Schema) {
    if let Some(alternatives) = schema.remove("anyOf") {
        schema.insert("oneOf".into(), alternatives);
    }
}

fn generator() -> SchemaGenerator {
    SchemaSettings::draft2020_12()
        .with(|settings| {
            // Every fragment is written in place, so a nested type cannot point at a `$defs`
            // entry that the hand-written file does not have.
            settings.inline_subschemas = true;
        })
        .with_transform(RecursiveTransform(drop_null))
        .with_transform(RecursiveTransform(drop_integer_format))
        .with_transform(RecursiveTransform(drop_empty_default))
        .with_transform(RecursiveTransform(reject_unknown_keys))
        .with_transform(RecursiveTransform(describe_first))
        .into_generator()
}

fn fragment<T: JsonSchema>(generator: &mut SchemaGenerator) -> Value {
    let mut schema = generator.root_schema_for::<T>();
    let object = schema.ensure_object();
    // The root-only keys belong to the whole file, not to one of its sections.
    object.remove("$schema");
    object.remove("title");
    schema.to_value()
}

/// TOML has no null, so an `Option` field is optional but never nullable, and it has no
/// default to show.
fn drop_null(schema: &mut Schema) {
    if schema.get("default") == Some(&Value::Null) {
        schema.remove("default");
    }
    if let Some(Value::Array(values)) = schema.get_mut("enum") {
        values.retain(|v| !v.is_null());
    }
    if let Some(Value::Array(types)) = schema.get_mut("type") {
        types.retain(|t| t != "null");
        if let [only] = types.as_slice() {
            let only = only.clone();
            schema.insert("type".into(), only);
        }
    }
    // An optional value with no single `type`, such as an enum of shapes, comes back as
    // `anyOf: [<value>, {"type": "null"}]`.
    let Some(Value::Array(alternatives)) = schema.get_mut("anyOf") else {
        return;
    };
    alternatives.retain(|alternative| alternative.get("type") != Some(&Value::from("null")));
    if let [Value::Object(only)] = alternatives.as_slice() {
        let only = only.clone();
        schema.remove("anyOf");
        let object = schema.ensure_object();
        for (key, value) in only {
            object.entry(key).or_insert(value);
        }
    }
}

/// A default of `[]`, `{}` or `""` says nothing an editor can use.
fn drop_empty_default(schema: &mut Schema) {
    let empty = match schema.get("default") {
        Some(Value::Array(values)) => values.is_empty(),
        Some(Value::Object(values)) => values.is_empty(),
        Some(Value::String(value)) => value.is_empty(),
        _ => false,
    };
    if empty {
        schema.remove("default");
    }
}

/// TOML integers have no width, so `format: "uint16"` and the like say nothing to an editor,
/// and a strict validator rejects formats it does not know. The range stays.
fn drop_integer_format(schema: &mut Schema) {
    if schema.get("type") == Some(&Value::from("integer")) {
        schema.remove("format");
    }
}

/// mise warns about an unknown key, but the schema rejects it, so an editor flags the typo.
///
/// A type that accepts open keys says so with an explicit `additionalProperties`, which this
/// leaves alone. Only a typed object is closed: an `if`, `then` or `oneOf` branch that lists
/// `properties` constrains those keys without describing the whole table.
fn reject_unknown_keys(schema: &mut Schema) {
    let Some(object) = schema.as_object_mut() else {
        return;
    };
    if object.get("type") == Some(&Value::from("object"))
        && object.contains_key("properties")
        && !object.contains_key("additionalProperties")
        && !object.contains_key("unevaluatedProperties")
    {
        object.insert("additionalProperties".into(), false.into());
    }
}

/// Puts `type` and `description` first, the way the hand-written sections read.
fn describe_first(schema: &mut Schema) {
    let Some(object) = schema.as_object_mut() else {
        return;
    };
    let mut rest = std::mem::take(object);
    for key in ["type", "description"] {
        if let Some(value) = rest.shift_remove(key) {
            object.insert(key.into(), value);
        }
    }
    object.extend(rest);
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn schema_json_is_up_to_date() {
        let path = concat!(env!("CARGO_MANIFEST_DIR"), "/../../schema/mise.json");
        let committed: Value =
            serde_json::from_str(&std::fs::read_to_string(path).unwrap()).unwrap();
        for (pointer, generated) in fragments() {
            assert_eq!(
                committed.pointer(pointer),
                Some(&generated),
                "schema/mise.json{pointer} differs from the mise-config types; run `mise run render:schema`"
            );
        }
    }
}
