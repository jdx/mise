#!/usr/bin/env bash
# Idempotent Cloud Agent bootstrap. Safe to rerun; does not start long-lived processes.
#
# Host packages are a subset of packaging/e2e/Dockerfile: enough to build mise and
# run most e2e tests (zsh/fish/direnv/python/jq/build tools). GUI libraries and
# a JDK are omitted; those belong in the dedicated e2e image.
set -euo pipefail

# environment.json does not set a working directory. Anchor to the repo root
# derived from this script so Cargo.toml, cargo build, and the mise symlink
# resolve correctly even if the runner starts elsewhere.
repo_root="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")/.." && pwd -P)"
cd "$repo_root"

# Draft builds and some Cloud Agent images run as `ubuntu`, not root.
if [ "$(id -u)" -eq 0 ]; then
	SUDO=()
else
	SUDO=(sudo -n)
fi

# sudo -n resets the environment; pass DEBIAN_FRONTEND through env so apt-get
# actually sees it (same pattern as src/system/sudo.rs).
apt_get() {
	"${SUDO[@]}" env DEBIAN_FRONTEND=noninteractive apt-get "$@"
}

apt_get update
apt_get install -y --no-install-recommends \
	autoconf \
	bison \
	build-essential \
	ca-certificates \
	curl \
	direnv \
	fish \
	git \
	jq \
	libffi-dev \
	libicu-dev \
	libncurses-dev \
	libreadline-dev \
	libssl-dev \
	libxml2-dev \
	libyaml-dev \
	openssh-client \
	pkg-config \
	python-is-python3 \
	python3 \
	python3-pip \
	python3-venv \
	unzip \
	xz-utils \
	zlib1g-dev \
	zsh

# Root-owned cargo/rustup homes from a snapshot are not usable by `ubuntu`.
if [ "$(id -u)" -ne 0 ]; then
	if [ -d /usr/local/cargo ]; then
		"${SUDO[@]}" chmod -R a+rwX /usr/local/cargo
	fi
	if [ -d /usr/local/rustup ]; then
		"${SUDO[@]}" chmod -R a+rwX /usr/local/rustup
	fi
fi

# aube's lock dir is /tmp/fslock. Recreate it if a leftover symlink is in the
# way so the privileged chmod cannot follow that path to another directory.
fslock=/tmp/fslock
if [ -L "$fslock" ]; then
	"${SUDO[@]}" rm -f "$fslock"
fi
"${SUDO[@]}" mkdir -p "$fslock"
if [ -L "$fslock" ] || [ ! -d "$fslock" ]; then
	echo "refusing to chmod $fslock: not a real directory" >&2
	exit 1
fi
"${SUDO[@]}" chmod 1777 "$fslock"

msrv="$(sed -n 's/^rust-version = "\(.*\)"/\1/p' Cargo.toml | head -n1)"
if [ -z "$msrv" ]; then
	echo "failed to parse rust-version from Cargo.toml" >&2
	exit 1
fi

rustup toolchain install "$msrv" --profile minimal --no-self-update -c rustfmt,clippy
rustup default "$msrv"

cargo build --all-features
"${SUDO[@]}" ln -sfn "$PWD/target/debug/mise" /usr/local/bin/mise
hash -r

export MISE_YES=1

# Keep GITHUB_TOKEN and MISE_GITHUB_TOKEN in sync. mise backends do not all
# read the same name; copy whichever is set, and only then fall back to gh.
if [ -n "${GITHUB_TOKEN:-}" ] && [ -z "${MISE_GITHUB_TOKEN:-}" ]; then
	export MISE_GITHUB_TOKEN="$GITHUB_TOKEN"
elif [ -n "${MISE_GITHUB_TOKEN:-}" ] && [ -z "${GITHUB_TOKEN:-}" ]; then
	export GITHUB_TOKEN="$MISE_GITHUB_TOKEN"
elif [ -z "${GITHUB_TOKEN:-}" ] && [ -z "${MISE_GITHUB_TOKEN:-}" ]; then
	if token="$(gh auth token 2>/dev/null)"; then
		export GITHUB_TOKEN="$token"
		export MISE_GITHUB_TOKEN="$token"
	fi
fi

# Re-export gh credentials in later shells without writing the token to disk.
# Isolated e2e runs inherit MISE_GITHUB_TOKEN/GITHUB_TOKEN from the parent.
github_token_profile=/etc/profile.d/mise-dev-github-token.sh
"${SUDO[@]}" tee "$github_token_profile" >/dev/null <<'EOF'
# Generated by .cursor/install.sh — do not store secrets here.
if [ -n "${GITHUB_TOKEN:-}" ] && [ -z "${MISE_GITHUB_TOKEN:-}" ]; then
	export MISE_GITHUB_TOKEN="$GITHUB_TOKEN"
elif [ -n "${MISE_GITHUB_TOKEN:-}" ] && [ -z "${GITHUB_TOKEN:-}" ]; then
	export GITHUB_TOKEN="$MISE_GITHUB_TOKEN"
elif [ -z "${GITHUB_TOKEN:-}" ] && [ -z "${MISE_GITHUB_TOKEN:-}" ] && command -v gh >/dev/null 2>&1; then
	if token="$(gh auth token 2>/dev/null)"; then
		export GITHUB_TOKEN="$token"
		export MISE_GITHUB_TOKEN="$token"
	fi
fi
EOF
"${SUDO[@]}" chmod 644 "$github_token_profile"

# Install tools without executing checkout-controlled hooks, templates, or
# [env], and without auto-trusting the branch. Tokens stay set so GitHub API
# calls during install are authenticated; MISE_SAFE=1 is the boundary that
# keeps those credentials away from project hooks.
eval "$(MISE_SAFE=1 mise activate bash --shims)"
MISE_SAFE=1 mise install
# Persist trust for later agent commands (tasks, exec). Install itself used
# safe mode so a branch-defined preinstall/postinstall hook could not run
# with GITHUB_TOKEN / MISE_GITHUB_TOKEN.
mise trust
hk install --mise

# Snapshots keep disk state but reset process env, so `eval "$(mise activate …)"`
# from this script does not survive into later agent shells. Persist shims via
# profile.d (login shells, including sh/dash from /etc/profile) and bash.bashrc
# (interactive non-login bash). POSIX PATH prepend — not `mise activate bash`.
shims_profile=/etc/profile.d/mise-dev-shims.sh
"${SUDO[@]}" tee "$shims_profile" >/dev/null <<'EOF'
# Generated by .cursor/install.sh
mise_shims="${HOME}/.local/share/mise/shims"
if [ -d "$mise_shims" ]; then
	case ":${PATH}:" in
	*":$mise_shims:"*) ;;
	*) PATH="$mise_shims:$PATH" ;;
	esac
	export PATH
fi
EOF
"${SUDO[@]}" chmod 644 "$shims_profile"

bashrc=/etc/bash.bashrc
if [ -f "$bashrc" ] && ! grep -qF "mise-dev-github-token" "$bashrc"; then
	"${SUDO[@]}" tee -a "$bashrc" >/dev/null <<'EOF'
# mise-dev-github-token — Cloud Agent non-login interactive bash
if [ -f /etc/profile.d/mise-dev-github-token.sh ]; then
	# shellcheck disable=SC1091
	. /etc/profile.d/mise-dev-github-token.sh
fi
EOF
fi

if [ -f "$bashrc" ] && ! grep -qF "mise-dev-shims" "$bashrc"; then
	"${SUDO[@]}" tee -a "$bashrc" >/dev/null <<'EOF'
# mise-dev-shims — Cloud Agent non-login interactive bash
if [ -f /etc/profile.d/mise-dev-shims.sh ]; then
	# shellcheck disable=SC1091
	. /etc/profile.d/mise-dev-shims.sh
fi
EOF
fi

# Isolated e2e PATH includes /usr/local/bin but not the agent's mise shims.
# Point at the real binaries so require_cmd node/npm and non-interactive `hk`
# work without putting them on /usr/bin (test_backend_missing_deps uses
# PATH=/usr/bin:/bin).
for cmd in node npm npx hk; do
	if bin="$(mise which "$cmd" 2>/dev/null)"; then
		"${SUDO[@]}" ln -sfn "$bin" "/usr/local/bin/$cmd"
	fi
done
